    /// </summary>
    /// <example><code>
    /// await client.Medications.ListAsync(
    ///     new ListMedicationsRequest { PracticeId = "prac_01j2y8m6jcc9tt24af5pw9x1bc" }
    /// );
    /// </code></example>
    public async Task<Pager<Medication>> ListAsync(
        ListMedicationsRequest request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
    {
        if (request is not null)
        {
            request = request with { };
        }
        var pager = await CursorPager<
            ListMedicationsRequest,
            RequestOptions?,
            MedicationList,
            string?,
            Medication
        >
            .CreateInstanceAsync(
                request,
                options,
                async (request, options, cancellationToken) =>
                    await ListInternalAsync(request, options, cancellationToken).WithRawResponse(),
                (request, cursor) =>
                {
                    request.StartingAfter = cursor;
                },
                response => response.NextCursor,
                response => response.Data?.ToList(),
                cancellationToken
            )
            .ConfigureAwait(false);
        return pager;
    }

